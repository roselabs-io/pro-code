#!/usr/bin/env python3
"""Regenerate each eval case's prompt.md from its template and the rubric it grades against.

A grader's rubric is a file the orchestrator reads and injects into a fresh sub-agent; the eval
sandbox cannot read the plugin's own source, so a case carries the rubric text in
`append_system_prompt` instead. That copy drifts. Run this after editing a rubric or a template;
prompt.md is generated and never edited by hand.
"""

from __future__ import annotations

import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent

# case name -> the files whose text is injected, in order.
SOURCES: dict[str, list[pathlib.Path]] = {
    # GATE 0. The grader def plus the contract it grades against: at run time the orchestrator
    # hands the sub-agent both, so a mutation has to remove the rule from both.
    "profile-completeness": [
        ROOT / "graders" / "profile-completeness.md",
        ROOT / "profiles" / "CONTRACT.md",
    ],
    # The profile hooks each of these reads are stated inline in the case, not injected.
    "plan-completeness": [ROOT / "graders" / "plan-completeness.md"],
    "frame-completeness": [ROOT / "graders" / "frame-completeness.md"],
}


def indent(text: str, by: str = "  ") -> str:
    return "\n".join(by + line if line.strip() else "" for line in text.splitlines())


def main() -> int:
    for case, sources in SOURCES.items():
        template = HERE / case / "prompt.tmpl.md"
        rubric = "\n\n".join(p.read_text() for p in sources)
        rendered = template.read_text().replace("{{RUBRIC}}", indent(rubric))
        (HERE / case / "prompt.md").write_text(
            "<!-- generated by evals/build.py — edit prompt.tmpl.md or the rubric, then rerun -->\n"
            + rendered
        )
        print(f"  wrote {case}/prompt.md from {len(sources)} source(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
